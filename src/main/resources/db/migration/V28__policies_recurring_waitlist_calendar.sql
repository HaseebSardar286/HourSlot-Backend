-- Phase 2: cancellation / no-show policy, reliability tracking, recurring bookings, waitlist, calendar feed.

-- Per-business booking policy. One row per business; absent row = defaults (free cancellation any time).
CREATE TABLE IF NOT EXISTS business_policies (
    business_id                 BIGINT PRIMARY KEY REFERENCES businesses(id) ON DELETE CASCADE,
    free_cancel_hours           INT NOT NULL DEFAULT 0,
    late_cancel_fee_percent     NUMERIC(5,2) NOT NULL DEFAULT 0,
    no_show_fee_percent         NUMERIC(5,2) NOT NULL DEFAULT 0,
    -- After this many no-shows at the business a customer must pay online up front; 0 = never.
    prepay_after_no_shows       INT NOT NULL DEFAULT 0,
    policy_text                 TEXT,
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Every cancellation and no-show, with who caused it and whether the policy made it chargeable.
CREATE TABLE IF NOT EXISTS booking_incidents (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id        BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    business_id       BIGINT NOT NULL REFERENCES businesses(id),
    customer_user_id  BIGINT REFERENCES users(id),
    -- CUSTOMER_CANCEL | CUSTOMER_LATE_CANCEL | PROVIDER_CANCEL | NO_SHOW
    kind              VARCHAR(32) NOT NULL,
    hours_before      NUMERIC(8,2),
    fee_amount        NUMERIC(12,2) NOT NULL DEFAULT 0,
    -- OWED | WAIVED | COLLECTED | NONE
    fee_status        VARCHAR(16) NOT NULL DEFAULT 'NONE',
    reason            TEXT,
    created_by        BIGINT REFERENCES users(id),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_incidents_booking ON booking_incidents (booking_id);
CREATE INDEX IF NOT EXISTS idx_booking_incidents_customer ON booking_incidents (customer_user_id, business_id);
CREATE INDEX IF NOT EXISTS idx_booking_incidents_business ON booking_incidents (business_id, kind);

-- Recurring bookings: a series groups the individual bookings it created.
CREATE TABLE IF NOT EXISTS booking_series (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_user_id  BIGINT NOT NULL REFERENCES users(id),
    business_id       BIGINT NOT NULL REFERENCES businesses(id),
    frequency         VARCHAR(16) NOT NULL,
    occurrences       INT NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS booking_series_items (
    series_id   BIGINT NOT NULL REFERENCES booking_series(id) ON DELETE CASCADE,
    booking_id  BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    PRIMARY KEY (series_id, booking_id)
);

-- Customers waiting for a slot on a given day; notified when a matching booking is cancelled.
-- waitlist_entries already exists from V2 (unused until now); extend it rather than replace it.
ALTER TABLE waitlist_entries ADD COLUMN IF NOT EXISTS desired_date DATE;
ALTER TABLE waitlist_entries ADD COLUMN IF NOT EXISTS notified_at TIMESTAMPTZ;
UPDATE waitlist_entries SET desired_date = (preferred_start AT TIME ZONE 'UTC')::date
WHERE desired_date IS NULL AND preferred_start IS NOT NULL;
-- Status values used from here on: ACTIVE | NOTIFIED | CANCELLED (legacy OPEN rows count as ACTIVE).
UPDATE waitlist_entries SET status = 'ACTIVE' WHERE status = 'OPEN';
ALTER TABLE waitlist_entries ALTER COLUMN status SET DEFAULT 'ACTIVE';
CREATE UNIQUE INDEX IF NOT EXISTS uq_waitlist_active
    ON waitlist_entries (customer_user_id, branch_id, service_id, desired_date) WHERE status = 'ACTIVE';
CREATE INDEX IF NOT EXISTS idx_waitlist_lookup ON waitlist_entries (branch_id, desired_date, status);

-- Secret per-business iCalendar feed URL (Google / Outlook / Apple calendar subscription).
CREATE TABLE IF NOT EXISTS calendar_feeds (
    business_id  BIGINT PRIMARY KEY REFERENCES businesses(id) ON DELETE CASCADE,
    token        VARCHAR(64) NOT NULL UNIQUE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
