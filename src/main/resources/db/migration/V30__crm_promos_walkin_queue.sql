-- Phase 3: customer records (tags; notes reuse customer_business_notes from V2), promo codes, walk-in queue.

CREATE TABLE IF NOT EXISTS customer_business_tags (
    business_id       BIGINT NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    customer_user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    tag               VARCHAR(40) NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (business_id, customer_user_id, tag)
);
CREATE INDEX IF NOT EXISTS idx_customer_business_notes_lookup
    ON customer_business_notes (business_id, customer_user_id, created_at DESC);

-- Codes a business hands out ("EID20"); applied by the customer when booking.
CREATE TABLE IF NOT EXISTS promo_codes (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id           BIGINT NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    code                  VARCHAR(32) NOT NULL,
    -- PERCENT | FIXED
    discount_type         VARCHAR(16) NOT NULL,
    discount_value        NUMERIC(12,2) NOT NULL,
    min_amount            NUMERIC(12,2) NOT NULL DEFAULT 0,
    valid_from            TIMESTAMPTZ,
    valid_until           TIMESTAMPTZ,
    -- NULL = unlimited
    max_uses              INT,
    per_customer_limit    INT NOT NULL DEFAULT 1,
    active                BOOLEAN NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_promo_codes_business_code ON promo_codes (business_id, UPPER(code));

-- One row per booking that used a code. Deleted if the booking is cancelled, so the use is given back.
CREATE TABLE IF NOT EXISTS promo_redemptions (
    booking_id        BIGINT PRIMARY KEY REFERENCES bookings(id) ON DELETE CASCADE,
    promo_code_id     BIGINT NOT NULL REFERENCES promo_codes(id) ON DELETE CASCADE,
    customer_user_id  BIGINT NOT NULL REFERENCES users(id),
    discount_amount   NUMERIC(12,2) NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_promo_redemptions_code ON promo_redemptions (promo_code_id, customer_user_id);

-- Walk-in queue: customers who turn up without a booking get a ticket number for the day.
CREATE TABLE IF NOT EXISTS queue_entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    queue_date     DATE NOT NULL,
    ticket_number  INT NOT NULL,
    customer_name  VARCHAR(120) NOT NULL,
    phone          VARCHAR(32),
    service_id     BIGINT REFERENCES services(id),
    -- WAITING | SERVING | DONE | LEFT
    status         VARCHAR(16) NOT NULL DEFAULT 'WAITING',
    called_at      TIMESTAMPTZ,
    finished_at    TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (business_id, queue_date, ticket_number)
);
CREATE INDEX IF NOT EXISTS idx_queue_entries_today ON queue_entries (business_id, queue_date, status);
