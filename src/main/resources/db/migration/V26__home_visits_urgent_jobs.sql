-- Phase 1 trades core: home-visit bookings, urgent ("available now") bookings,
-- job materials, customer sign-off and offline (cash) payment collection.

-- Where and how a home-visit booking happens. Kept beside bookings so the core booking row is unchanged.
CREATE TABLE IF NOT EXISTS booking_visits (
    booking_id              BIGINT PRIMARY KEY REFERENCES bookings(id) ON DELETE CASCADE,
    customer_address_id     BIGINT REFERENCES customer_addresses(id),
    address_text            TEXT,
    latitude                DOUBLE PRECISION,
    longitude               DOUBLE PRECISION,
    arrival_window_minutes  INT NOT NULL DEFAULT 0,
    urgent                  BOOLEAN NOT NULL DEFAULT FALSE,
    urgent_fee              NUMERIC(12,2) NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Arrival window promised to the customer ("arrive between 14:00 and 16:00"); 0 = exact time.
ALTER TABLE services ADD COLUMN IF NOT EXISTS arrival_window_minutes INT NOT NULL DEFAULT 0;
-- Extra charge for urgent bookings, as a percentage of the service price.
ALTER TABLE services ADD COLUMN IF NOT EXISTS urgent_surcharge_percent NUMERIC(5,2) NOT NULL DEFAULT 0;

-- Provider is taking urgent jobs until this time; NULL or past = not available now.
ALTER TABLE businesses ADD COLUMN IF NOT EXISTS available_now_until TIMESTAMPTZ;

ALTER TABLE jobs ADD COLUMN IF NOT EXISTS customer_confirmed_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS job_materials (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id      BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
    name        VARCHAR(200) NOT NULL,
    quantity    NUMERIC(10,2) NOT NULL DEFAULT 1,
    unit_price  NUMERIC(12,2) NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_job_materials_job ON job_materials (job_id);
