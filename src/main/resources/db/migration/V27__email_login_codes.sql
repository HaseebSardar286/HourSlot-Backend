-- Passwordless sign-in: one-time 6-digit codes sent by email. Only a hash of the code is stored.
CREATE TABLE IF NOT EXISTS email_login_codes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(255) NOT NULL,
    code_hash    VARCHAR(64) NOT NULL,
    attempts     INT NOT NULL DEFAULT 0,
    expires_at   TIMESTAMPTZ NOT NULL,
    consumed_at  TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_email_login_codes_email_created ON email_login_codes (LOWER(email), created_at DESC);
