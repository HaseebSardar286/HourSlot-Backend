-- 1:1 org per existing business owner
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'businesses' AND column_name = 'owner_id') THEN
        EXECUTE $sql$
            INSERT INTO organizations (name, slug, billing_email, status, default_currency, created_at, updated_at)
            SELECT DISTINCT
                COALESCE(NULLIF(b.name, ''), 'Organization') || ' Org',
                'org-' || u.id::text,
                u.email,
                'ACTIVE',
                'USD',
                COALESCE(b.created_at, NOW()),
                NOW()
            FROM businesses b
            JOIN users u ON u.id = b.owner_id
            WHERE NOT EXISTS (SELECT 1 FROM organizations o WHERE o.slug = 'org-' || u.id::text)
        $sql$;
        EXECUTE $sql$
            INSERT INTO organization_members (organization_id, user_id, status, joined_at, created_at)
            SELECT o.id, u.id, 'ACTIVE', NOW(), NOW()
            FROM businesses b
            JOIN users u ON u.id = b.owner_id
            JOIN organizations o ON o.slug = 'org-' || u.id::text
            WHERE NOT EXISTS (
                SELECT 1 FROM organization_members om
                WHERE om.organization_id = o.id AND om.user_id = u.id
            )
        $sql$;
        EXECUTE $sql$
            UPDATE businesses b
            SET organization_id = o.id
            FROM users u, organizations o
            WHERE u.id = b.owner_id
              AND o.slug = 'org-' || u.id::text
              AND b.organization_id IS NULL
        $sql$;
    END IF;
END $$;

