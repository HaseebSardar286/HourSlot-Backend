    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id  BIGINT NOT NULL REFERENCES resources(id) ON DELETE CASCADE,
    start_at     TIMESTAMPTZ NOT NULL,
    end_at       TIMESTAMPTZ NOT NULL,
    reason       VARCHAR(255)
);

DO $$
DECLARE
    rec RECORD;
    new_id BIGINT;
    br RECORD;
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'working_hours') THEN
        FOR rec IN SELECT * FROM working_hours WHERE staff_id IS NULL LOOP
            INSERT INTO branch_working_hours (branch_id, day_of_week, start_time, end_time, closed)
            VALUES (rec.branch_id, rec.day_of_week, rec.start_time, rec.end_time, rec.closed)
            RETURNING id INTO new_id;
            IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'breaks') THEN
                INSERT INTO branch_breaks (working_hour_id, start_time, end_time)
                SELECT new_id, start_time, end_time FROM breaks WHERE working_hour_id = rec.id;
            END IF;
        END LOOP;

        FOR rec IN SELECT * FROM working_hours WHERE staff_id IS NOT NULL LOOP
            INSERT INTO staff_working_hours (staff_id, day_of_week, start_time, end_time, closed)
            VALUES (rec.staff_id, rec.day_of_week, rec.start_time, rec.end_time, rec.closed)
            RETURNING id INTO new_id;
            IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'breaks') THEN
                INSERT INTO staff_breaks (working_hour_id, start_time, end_time)
                SELECT new_id, start_time, end_time FROM breaks WHERE working_hour_id = rec.id;
            END IF;
        END LOOP;
    END IF;

    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'holidays') THEN
        INSERT INTO branch_holidays (branch_id, holiday_date, description)
        SELECT branch_id, date, description FROM holidays WHERE staff_id IS NULL;

        INSERT INTO staff_time_off (staff_id, start_at, end_at, reason, status)
        SELECT staff_id,
               date::timestamp,
               (date + 1)::timestamp - INTERVAL '1 second',
               description,
               'APPROVED'
        FROM holidays
        WHERE staff_id IS NOT NULL;
    END IF;
END $$;

