    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'businesses' AND column_name = 'gallery_urls') THEN
        FOR rec IN SELECT id, gallery_urls FROM businesses WHERE gallery_urls IS NOT NULL AND gallery_urls <> '' LOOP
            idx := 0;
            FOREACH url IN ARRAY string_to_array(rec.gallery_urls, ',') LOOP
                url := trim(url);
                IF url <> '' THEN
                    INSERT INTO media_assets (owner_type, owner_id, storage_key, url, mime_type, sort_order, created_at)
