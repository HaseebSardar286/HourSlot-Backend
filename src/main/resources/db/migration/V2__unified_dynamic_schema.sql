-- Unified dynamic schema + in-place data migration from the Hibernate-era model.
-- Safe on both existing Neon databases and empty installs.

CREATE OR REPLACE FUNCTION hourslot_rename_column(tbl text, oldc text, newc text) RETURNS void AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = tbl AND column_name = oldc
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = tbl AND column_name = newc
    ) THEN
        EXECUTE format('ALTER TABLE %I RENAME COLUMN %I TO %I', tbl, oldc, newc);
    END IF;
END;
$$ LANGUAGE plpgsql;

