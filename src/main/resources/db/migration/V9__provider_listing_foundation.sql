-- ---------------------------------------------------------------------------
-- Named geographic areas (admin-managed)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS geo_areas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code  VARCHAR(8) NOT NULL,
    region        VARCHAR(128),
    city          VARCHAR(128) NOT NULL,
    name          VARCHAR(128) NOT NULL,
    slug          VARCHAR(160) NOT NULL,
    latitude      DOUBLE PRECISION,
    longitude     DOUBLE PRECISION,
    status        VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ,
    deleted_at    TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_geo_areas_country_city_slug_live
    ON geo_areas (country_code, city, slug)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_geo_areas_city
    ON geo_areas (country_code, city)
    WHERE deleted_at IS NULL AND status = 'ACTIVE';

-- ---------------------------------------------------------------------------
-- Business service coverage
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS business_service_areas (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT NOT NULL REFERENCES businesses(id),
    coverage_type  VARCHAR(32) NOT NULL,
    geo_area_id    BIGINT REFERENCES geo_areas(id),
    area_name      VARCHAR(128),
    latitude       DOUBLE PRECISION,
    longitude      DOUBLE PRECISION,
    radius_km      NUMERIC(8,2),
    status         VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ,
    deleted_at     TIMESTAMPTZ,
    CONSTRAINT chk_bsa_coverage_type CHECK (coverage_type IN ('NAMED', 'RADIUS')),
    CONSTRAINT chk_bsa_named CHECK (
        coverage_type <> 'NAMED' OR geo_area_id IS NOT NULL
    ),
    CONSTRAINT chk_bsa_radius CHECK (
        coverage_type <> 'RADIUS'
        OR (latitude IS NOT NULL AND longitude IS NOT NULL AND radius_km IS NOT NULL AND radius_km > 0 AND radius_km <= 50)
    )
);

CREATE INDEX IF NOT EXISTS idx_business_service_areas_business
    ON business_service_areas (business_id)
    WHERE deleted_at IS NULL AND status = 'ACTIVE';

-- ---------------------------------------------------------------------------
-- Customer saved addresses
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS customer_addresses (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_user_id   BIGINT NOT NULL REFERENCES users(id),
    label              VARCHAR(64) NOT NULL,
    address_line       VARCHAR(512) NOT NULL,
    country_code       VARCHAR(8) NOT NULL,
    region             VARCHAR(128),
    city               VARCHAR(128),
    area_name          VARCHAR(128),
    postal_code        VARCHAR(32),
    geo_area_id        BIGINT REFERENCES geo_areas(id),
    latitude           DOUBLE PRECISION,
    longitude          DOUBLE PRECISION,
    is_default         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ,
    deleted_at         TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_customer_addresses_default_live
    ON customer_addresses (customer_user_id)
    WHERE is_default = TRUE AND deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_customer_addresses_user
    ON customer_addresses (customer_user_id)
    WHERE deleted_at IS NULL;

