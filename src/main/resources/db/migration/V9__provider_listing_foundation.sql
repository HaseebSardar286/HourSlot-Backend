    cp.user_id,
    'Home',
    cp.address_line1,
    COALESCE(NULLIF(cp.country_code, ''), 'PK'),
    cp.region,
    cp.city,
    cp.postal_code,
    TRUE,
    COALESCE(cp.created_at, NOW())
FROM customer_profiles cp
WHERE cp.deleted_at IS NULL
  AND cp.address_line1 IS NOT NULL
  AND TRIM(cp.address_line1) <> ''
  AND NOT EXISTS (
      SELECT 1 FROM customer_addresses ca
      WHERE ca.customer_user_id = cp.user_id AND ca.deleted_at IS NULL
  );

