-- Phase 1 provider listing foundation.
-- Provider = businesses façade; individuals get implicit org/business/branch/staff.

-- ---------------------------------------------------------------------------
-- Organizations
-- ---------------------------------------------------------------------------
ALTER TABLE organizations
    ADD COLUMN IF NOT EXISTS listing_mode VARCHAR(32) NOT NULL DEFAULT 'BUSINESS';

UPDATE organizations SET listing_mode = 'BUSINESS' WHERE listing_mode IS NULL OR listing_mode = '';

-- ---------------------------------------------------------------------------
-- Businesses (public listing façade)
-- ---------------------------------------------------------------------------
ALTER TABLE businesses
    ADD COLUMN IF NOT EXISTS listing_mode VARCHAR(32) NOT NULL DEFAULT 'BUSINESS',
    ADD COLUMN IF NOT EXISTS provider_type VARCHAR(32) NOT NULL DEFAULT 'BUSINESS',
    ADD COLUMN IF NOT EXISTS service_mode VARCHAR(32) NOT NULL DEFAULT 'AT_PROVIDER',
    ADD COLUMN IF NOT EXISTS publish_status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    ADD COLUMN IF NOT EXISTS onboarding_state VARCHAR(32) NOT NULL DEFAULT 'STARTED',
    ADD COLUMN IF NOT EXISTS years_experience INT,
    ADD COLUMN IF NOT EXISTS travel_buffer_minutes INT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS phone VARCHAR(64);

UPDATE businesses
SET listing_mode = COALESCE(NULLIF(listing_mode, ''), 'BUSINESS'),
    provider_type = COALESCE(NULLIF(provider_type, ''), 'BUSINESS'),
    service_mode = COALESCE(NULLIF(service_mode, ''), 'AT_PROVIDER'),
    travel_buffer_minutes = COALESCE(travel_buffer_minutes, 0);

UPDATE businesses
SET publish_status = CASE
        WHEN status = 'APPROVED' THEN 'PUBLISHED'
        ELSE 'DRAFT'
    END
WHERE publish_status IS NULL OR publish_status = '' OR publish_status = 'DRAFT';

-- Re-apply carefully: only backfill rows that still look like defaults from ADD COLUMN
UPDATE businesses
SET publish_status = 'PUBLISHED'
WHERE status = 'APPROVED' AND publish_status = 'DRAFT';

UPDATE businesses
SET onboarding_state = CASE
        WHEN status = 'APPROVED' THEN 'PUBLISHED'
        ELSE COALESCE(NULLIF(onboarding_state, ''), 'STARTED')
    END;

UPDATE businesses
SET provider_type = 'INDIVIDUAL'
WHERE listing_mode = 'INDIVIDUAL' AND provider_type <> 'INDIVIDUAL';

